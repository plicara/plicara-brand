"""Build the Foothills Labs logo set from the Siwalik contour mark.

The mark itself comes from ../marks/contour-siwalik.svg, which is generated by
../marks/generate.py. This script only reframes it, bakes colour variants, and
composes the lockups — the wordmark is converted to outlines so the SVGs carry
no font dependency.

Requires fontTools, uharfbuzz, and the Archivo variable font:

    npm install @fontsource-variable/archivo
    pip install fonttools brotli uharfbuzz
    python3 build.py [path/to/archivo-latin-wdth-normal.woff2]

Archivo is SIL Open Font Licence 1.1 (Omnibus-Type). Outlines baked into these
files are covered by it; the OFL permits this and does not extend to the rest of
the repository.
"""

import io
import math
import os
import re
import sys

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.misc.transform import Transform
import uharfbuzz as hb

HERE = os.path.dirname(os.path.abspath(__file__))
FAMILY = os.path.join(HERE, "..", "marks")

FONT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "..", "..", "node_modules", "@fontsource-variable", "archivo",
    "files", "archivo-latin-wdth-normal.woff2")

C = {
    "signal": "#D9F224",
    "ink": "#0C1110",
    "moss": "#39441F",
    "paper": "#F2F3EC",
    "alpine": "#12688F",
}

TRACKING = 0.015  # em, opens the expanded caps up a little


# --- the mark ---------------------------------------------------------------
#
# Siwalik is CONSTRUCTED, not sampled. The seven summits are contoured from
# height fields by ../marks/generate.py, and that irregularity is the point for
# them — it is data. A logo is not data. It has to hold at 16 px, reproduce in
# one colour, and look deliberate at every size, so the house mark is drawn:
# one master curve, three true parallel offsets, even spacing, aligned ends.

BANDS, GAP, AMP, TILT, SKEW = 4, 19.0, 14.0, 5.0, 0.95


def master(t):
    """One ridge line across a 100-wide box. t in [0, 1]. SVG y-down."""
    return t * 100.0, AMP * math.sin(math.pi * (t ** SKEW)) - TILT * t


def bands(n=BANDS, gap=GAP, samples=400, points=12):
    """n parallel copies of the master curve at constant PERPENDICULAR distance.

    Translating the curve down n times would look wrong: the gaps pinch wherever
    the curve is steep. True offsets keep the air between bands even, which is
    the whole complaint this fixes.
    """
    pts = [master(i / (samples - 1)) for i in range(samples)]
    norms = []
    for i in range(samples):
        a, b = pts[max(0, i - 1)], pts[min(samples - 1, i + 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]
        L = math.hypot(dx, dy) or 1.0
        norms.append((-dy / L, dx / L))

    lines = [[(p[0] + nx * k * gap, p[1] + ny * k * gap)
              for p, (nx, ny) in zip(pts, norms)] for k in range(n)]

    # Trim to the x-range every band shares, so the stack has square edges
    # instead of stepping in and out.
    lo = max(min(p[0] for p in ln) for ln in lines)
    hi = min(max(p[0] for p in ln) for ln in lines)
    out = []
    for ln in lines:
        clip = [p for p in ln if lo <= p[0] <= hi] or ln
        out.append(_bezier(_even(clip, points)))
    return out


def _even(line, n):
    """Resample to n points at even arc length."""
    d = [0.0]
    for a, b in zip(line, line[1:]):
        d.append(d[-1] + math.hypot(b[0] - a[0], b[1] - a[1]))
    total = d[-1] or 1.0
    out = []
    for i in range(n):
        target = total * i / (n - 1)
        j = max(k for k in range(len(d)) if d[k] <= target) if target < total else len(line) - 2
        j = min(j, len(line) - 2)
        span = d[j + 1] - d[j] or 1.0
        f = (target - d[j]) / span
        out.append((line[j][0] + (line[j + 1][0] - line[j][0]) * f,
                    line[j][1] + (line[j + 1][1] - line[j][1]) * f))
    return out


def _bezier(pts, prec=2):
    """Open Catmull-Rom through the points, emitted as cubic beziers."""
    f = lambda v: f"{round(v, prec):g}"
    n = len(pts)
    d = [f"M{f(pts[0][0])} {f(pts[0][1])}"]
    for i in range(n - 1):
        p0, p1 = pts[max(0, i - 1)], pts[i]
        p2, p3 = pts[i + 1], pts[min(n - 1, i + 2)]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6.0, p1[1] + (p2[1] - p0[1]) / 6.0)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6.0, p2[1] - (p3[1] - p1[1]) / 6.0)
        d.append(f"C{f(c1[0])} {f(c1[1])} {f(c2[0])} {f(c2[1])} {f(p2[0])} {f(p2[1])}")
    return "".join(d)


def bbox(ds):
    pts = [(float(x), float(y)) for d in ds
           for x, y in re.findall(r"(-?[\d.]+) (-?[\d.]+)", d)]
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return min(xs), min(ys), max(xs), max(ys)


def reframe(ds, bb, box, pad, stroke):
    """Fit the mark into a `box` square with `pad` clear space on every side.

    The stroke's own half-width is held inside the padding, so a flush box is
    correct clear space at any size.
    """
    x0, y0, x1, y1 = bb
    w, h = x1 - x0, y1 - y0
    inner = box - 2 * pad - stroke
    k = inner / max(w, h)
    ox = pad + stroke / 2 + (inner - w * k) / 2
    oy = pad + stroke / 2 + (inner - h * k) / 2
    out = []
    for d in ds:
        def sub(m, k=k, x0=x0, y0=y0, ox=ox, oy=oy):
            x, y = float(m.group(1)), float(m.group(2))
            return f"{round(ox + (x - x0) * k, 2):g} {round(oy + (y - y0) * k, 2):g}"
        out.append(re.sub(r"(-?[\d.]+) (-?[\d.]+)", sub, d))
    return out, k


def mark_svg(ds, box, stroke, colour=None, ground=None, title="Foothills Labs",
             radius=0):
    col = colour or "currentColor"
    body = ""
    if ground:
        r = f' rx="{radius}"' if radius else ""
        body += f'<rect width="{box}" height="{box}"{r} fill="{ground}"/>'
    body += "".join(f'<path d="{d}"/>' for d in ds)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {box} {box}" '
        f'width="{box}" height="{box}" role="img" aria-label="{title}">'
        f'<title>{title}</title>'
        f'<g fill="none" stroke="{col}" stroke-width="{stroke}" '
        f'stroke-linecap="round" stroke-linejoin="round">{body}</g></svg>'
    ).replace(f'stroke-linejoin="round">{"<rect" if ground else ""}',
              f'stroke-linejoin="round">{"<rect" if ground else ""}')


def mark_group(ds, stroke, colour):
    return (f'<g fill="none" stroke="{colour}" stroke-width="{stroke}" '
            f'stroke-linecap="round" stroke-linejoin="round">'
            + "".join(f'<path d="{d}"/>' for d in ds) + "</g>")


# --- the wordmark -----------------------------------------------------------

def static_archivo(wght=800, wdth=125):
    f = TTFont(FONT)
    inst = instancer.instantiateVariableFont(f, {"wght": wght, "wdth": wdth})
    # Drop the woff2 wrapper — harfbuzz reads sfnt, and a compressed face parses
    # as empty, which shapes every character to .notdef.
    inst.flavor = None
    return inst


def shape(font, text, size):
    """Harfbuzz-shaped outline path for `text`, plus its advance width."""
    buf = io.BytesIO()
    font.save(buf)
    face = hb.Face(buf.getvalue())
    hbfont = hb.Font(face)
    upem = face.upem
    hbfont.scale = (upem, upem)

    buf2 = hb.Buffer()
    buf2.add_str(text)
    buf2.guess_segment_properties()
    hb.shape(hbfont, buf2, {"kern": True, "liga": True})

    order = font.getGlyphOrder()
    glyphset = font.getGlyphSet()
    scale = size / upem
    track = TRACKING * upem

    d, x = [], 0.0
    for info, pos in zip(buf2.glyph_infos, buf2.glyph_positions):
        name = order[info.codepoint]
        pen = SVGPathPen(glyphset, ntos=lambda v: f"{round(v, 2):g}")
        t = Transform(scale, 0, 0, -scale, (x + pos.x_offset) * scale, 0)
        glyphset[name].draw(TransformPen(pen, t))
        got = pen.getCommands()
        if got:
            d.append(got)
        x += pos.x_advance + track
    return " ".join(d), (x - track) * scale


def bbox_of(font, text, size):
    order = font.getGlyphOrder()
    glyphset = font.getGlyphSet()
    buf = io.BytesIO()
    font.save(buf)
    face = hb.Face(buf.getvalue())
    hbfont = hb.Font(face)
    upem = face.upem
    hbfont.scale = (upem, upem)
    b2 = hb.Buffer()
    b2.add_str(text)
    b2.guess_segment_properties()
    hb.shape(hbfont, b2, {"kern": True, "liga": True})
    scale = size / upem
    track = TRACKING * upem
    bp = BoundsPen(glyphset)
    x = 0.0
    for info, pos in zip(b2.glyph_infos, b2.glyph_positions):
        name = order[info.codepoint]
        t = Transform(scale, 0, 0, -scale, (x + pos.x_offset) * scale, 0)
        glyphset[name].draw(TransformPen(bp, t))
        x += pos.x_advance + track
    return bp.bounds  # (xMin, yMin, xMax, yMax) in SVG space, y already flipped


# --- outputs ----------------------------------------------------------------

def write(name, content):
    path = os.path.join(HERE, name)
    with open(path, "w") as fh:
        fh.write(content + "\n")
    print(f"  {name:38s} {len(content):>6,} B")


def main():
    base = bands()
    bb = bbox(base)

    BOX, PAD, STROKE = 64, 4, 3.4
    mark, _ = reframe(base, bb, BOX, PAD, STROKE)

    print("marks")
    write("mark.svg", mark_svg(mark, BOX, STROKE))
    for tone in ("signal", "moss", "ink", "paper"):
        write(f"mark-{tone}.svg", mark_svg(mark, BOX, STROKE, C[tone]))

    print("avatars and favicon")
    A, APAD, ASTROKE = 512, 74, 26.0
    av, _ = reframe(base, bb, A, APAD, ASTROKE)
    for name, ground, fg in (("ink", C["ink"], C["signal"]),
                             ("signal", C["signal"], C["ink"]),
                             ("moss", C["moss"], C["signal"]),
                             ("alpine", C["alpine"], C["paper"])):
        write(f"avatar-{name}.svg", mark_svg(av, A, ASTROKE, fg, ground=ground))
    # Same geometry, a hair more stroke — optical sizing, not a second shape.
    fav, _ = reframe(base, bb, 32, 3, 2.1)
    write("favicon.svg", mark_svg(fav, 32, 2.1, C["signal"], ground=C["ink"]))

    # Lockups. Cap height drives the optical match between mark and wordmark.
    font = static_archivo()
    print("lockups")
    THEMES = (("dark", C["signal"], C["paper"]),
              ("light", C["moss"], C["ink"]),
              ("signal", C["signal"], C["signal"]))
    for kind, lines, mark_px in (("horizontal", ["FOOTHILLS LABS"], 64.0),
                                 ("compact", ["FOOTHILLS", "LABS"], 78.0)):
        for theme, fg, wordfg in THEMES:
            write(f"lockup-{kind}-{theme}.svg",
                  lockup(font, base, bb, lines, fg, wordfg, mark_px))
    for theme, fg, wordfg in THEMES:
        write(f"lockup-vertical-{theme}.svg",
              vertical(font, base, bb, ["FOOTHILLS", "LABS"], fg, wordfg))

    # The family glyph is the same drawing at the family's stroke weight, so the
    # model sheet and the logo can never drift apart.
    print("family glyph")
    fam, _ = reframe(base, bb, 100, 6, 1.75)
    path = os.path.join(FAMILY, "contour-siwalik.svg")
    with open(path, "w") as fh:
        fh.write(mark_svg(fam, 100, 1.75) + "\n")
    print(f"  ../marks/contour-siwalik.svg")


def lockup(font, ds, bb, lines, mark_colour, word_colour, mark_px=64.0):
    SIZE = 44.0           # em size for the wordmark
    MARK = mark_px        # mark box
    STROKE = 3.0 * (mark_px / 64.0)
    GAP = 22.0
    LEAD = 0.86           # line height, in em, for the stacked cut

    caps = [bbox_of(font, t, SIZE) for t in lines]
    cap_top = min(b[1] for b in caps)
    cap_bot = max(b[3] for b in caps)
    cap_h = cap_bot - cap_top
    widths = []
    paths = []
    for i, t in enumerate(lines):
        d, _ = shape(font, t, SIZE)
        paths.append(d)
        widths.append(caps[i][2] - caps[i][0])

    if len(lines) == 1:
        text_h = cap_h
    else:
        text_h = cap_h + SIZE * LEAD * (len(lines) - 1)

    m, _ = reframe(ds, bb, MARK, 0, STROKE)
    word_w = max(widths)

    W = MARK + GAP + word_w
    H = max(MARK, text_h)
    mark_y = (H - MARK) / 2
    # Baselines: first line sits so the whole block is vertically centred.
    y0 = (H - text_h) / 2 - cap_top

    body = [f'<g transform="translate(0 {round(mark_y, 2):g})">'
            + mark_group(m, STROKE, mark_colour) + "</g>"]
    for i, d in enumerate(paths):
        dy = y0 + i * SIZE * LEAD
        body.append(f'<g fill="{word_colour}" transform="translate('
                    f'{round(MARK + GAP - caps[i][0], 2):g} {round(dy, 2):g})">'
                    f'<path d="{d}"/></g>')

    W, H = round(W, 2), round(H, 2)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:g} {H:g}" '
        f'width="{W:g}" height="{H:g}" role="img" aria-label="Foothills Labs">'
        f'<title>Foothills Labs</title>{"".join(body)}</svg>'
    )




def vertical(font, ds, bb, lines, mark_colour, word_colour):
    """Mark above, wordmark centred beneath. For README heroes and cards."""
    SIZE = 40.0
    MARK = 96.0
    STROKE = 4.4
    GAP = 26.0
    LEAD = 0.86

    caps = [bbox_of(font, t, SIZE) for t in lines]
    cap_top = min(b[1] for b in caps)
    cap_bot = max(b[3] for b in caps)
    text_h = (cap_bot - cap_top) + SIZE * LEAD * (len(lines) - 1)
    paths = [shape(font, t, SIZE)[0] for t in lines]
    widths = [b[2] - b[0] for b in caps]

    W = max(MARK, max(widths))
    H = MARK + GAP + text_h
    y0 = MARK + GAP - cap_top

    body = [f'<g transform="translate({round((W - MARK) / 2, 2):g} 0)">'
            + mark_group(reframe(ds, bb, MARK, 0, STROKE)[0], STROKE, mark_colour)
            + "</g>"]
    for i, d in enumerate(paths):
        dx = (W - widths[i]) / 2 - caps[i][0]
        dy = y0 + i * SIZE * LEAD
        body.append(f'<g fill="{word_colour}" transform="translate('
                    f'{round(dx, 2):g} {round(dy, 2):g})"><path d="{d}"/></g>')

    W, H = round(W, 2), round(H, 2)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W:g} {H:g}" '
        f'width="{W:g}" height="{H:g}" role="img" aria-label="Foothills Labs">'
        f'<title>Foothills Labs</title>{"".join(body)}</svg>'
    )

if __name__ == "__main__":
    main()
